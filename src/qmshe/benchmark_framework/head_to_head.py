WinnerChoice = Literal["System A", "System B", "Tie"]


@dataclass
class HeadToHeadResult:
    example_id: str
    system_a: str
    system_b: str
    comprehensiveness: WinnerChoice
    diversity: WinnerChoice
    empowerment: WinnerChoice
    directness: WinnerChoice
    overall: WinnerChoice
    reasoning: str = ""

    def to_dict(self) -> dict:
        return {
            "example_id": self.example_id,
            "system_a": self.system_a,
            "system_b": self.system_b,
            "comprehensiveness": self.comprehensiveness,
            "diversity": self.diversity,
            "empowerment": self.empowerment,
            "directness": self.directness,
            "overall": self.overall,
            "reasoning": self.reasoning,
        }


@dataclass
class WinRateSummary:
    system_a: str
    system_b: str
    total_pairs: int = 0
    comprehensiveness_win_rate: float = 0.0
    diversity_win_rate: float = 0.0
    empowerment_win_rate: float = 0.0
    directness_win_rate: float = 0.0
    overall_win_rate: float = 0.0

    @classmethod
    def from_results(cls, system_a: str, system_b: str, results: list[HeadToHeadResult]) -> WinRateSummary:
        if not results:
            return cls(system_a=system_a, system_b=system_b)
        
        def calc_win_rate(dimension: str) -> float:
            wins, ties = 0, 0
            for r in results:
                choice = getattr(r, dimension)
                if choice == "System A":
                    wins += 1
                elif choice == "Tie":
                    ties += 1
            return (wins + 0.5 * ties) / len(results)

        return cls(
            system_a=system_a,
            system_b=system_b,
            total_pairs=len(results),
            comprehensiveness_win_rate=calc_win_rate("comprehensiveness"),
            diversity_win_rate=calc_win_rate("diversity"),
            empowerment_win_rate=calc_win_rate("empowerment"),
            directness_win_rate=calc_win_rate("directness"),
            overall_win_rate=calc_win_rate("overall"),
        )
